#!/usr/bin/env python3
"""Generate and verify deduplicated entries for the kernel's builtin_fw table."""

import hashlib
import json
from pathlib import Path
import re
import struct
import sys


def manifest(root):
    directory = root / "nura-firmware"
    document = json.loads((directory / "manifest.json").read_text())
    if document.get("schema") != 1 or not document.get("files"):
        raise ValueError("Missing embedded firmware manifest; use nura/build.sh.")
    names = set()
    for entry in document["files"]:
        name, checksum = entry["name"], entry["sha256"]
        if (not re.fullmatch(r"[a-zA-Z0-9_./+-]+", name) or name.startswith("/")
                or ".." in Path(name).parts or name in names
                or not re.fullmatch(r"[0-9a-f]{64}", checksum)):
            raise ValueError(f"Invalid firmware entry: {name}")
        names.add(name)
        data = (directory / checksum).read_bytes()
        if not data or len(data) != entry["size"] or hashlib.sha256(data).hexdigest() != checksum:
            raise ValueError(f"Firmware checksum mismatch: {name}")
    return document


def prepare(root):
    document = manifest(root)
    config = (root / ".config").read_text()
    if not re.search(r"^CONFIG_FW_LOADER=y$", config, re.M) or not re.search(r"^CONFIG_64BIT=y$", config, re.M):
        raise ValueError("Built-in firmware requires CONFIG_FW_LOADER=y and a 64-bit kernel.")
    lines = ["/* Generated by embed-firmware.py; do not edit. */"]
    for checksum in sorted({entry["sha256"] for entry in document["files"]}):
        lines += ['.section .rodata,"a",@progbits', '.p2align 4', f"nura_fw_{checksum}:",
                  f'.incbin "nura-firmware/{checksum}"']
    for index, entry in enumerate(document["files"]):
        lines += ['.section .rodata.str,"aMS",@progbits,1', '.p2align 3', f"nura_fw_name_{index}:",
                  f'.asciz "{entry["name"]}"', '.section .builtin_fw,"a",@progbits', '.p2align 3',
                  f'.quad nura_fw_name_{index}, nura_fw_{entry["sha256"]}, {entry["size"]}']
    builtin = root / "drivers/base/firmware_loader/builtin"
    (builtin / "nura-firmware.S").write_text("\n".join(lines) + "\n")
    makefile = builtin / "Makefile"
    text = makefile.read_text()
    rule = "obj-y += nura-firmware.o\n"
    if rule not in text:
        makefile.write_text(text + "\n# Deduplicated firmware staged by Nura.\n" + rule)
    print(f"Embedded firmware: {len(document['files'])} request names.", flush=True)


class Elf:
    """Read linked ELF64 sections and symbols without host-specific binutils."""
    def __init__(self, path):
        self.data = path.read_bytes()
        if self.data[:6] != b"\x7fELF\x02\x01":
            raise ValueError("Expected a little-endian ELF64 image.")
        offset = struct.unpack_from("<Q", self.data, 40)[0]
        stride, count = struct.unpack_from("<HH", self.data, 58)
        self.sections = [struct.unpack_from("<IIQQQQIIQQ", self.data, offset + i * stride)
                         for i in range(count)]
        self.symbols = {}
        for section in self.sections:
            if section[1] != 2:
                continue
            strings = self.sections[section[6]]
            table = self.data[strings[4]:strings[4] + strings[5]]
            for position in range(section[4], section[4] + section[5], section[9]):
                name, _, _, _, value, _ = struct.unpack_from("<IBBHQQ", self.data, position)
                self.symbols[table[name:].split(b"\0", 1)[0].decode()] = value

    def read(self, address, size=None):
        for section in self.sections:
            if section[1] != 8 and section[2] & 2 and section[3] <= address < section[3] + section[5]:
                length = section[3] + section[5] - address
                if size is not None and size > length:
                    raise ValueError("Firmware pointer exceeds its ELF section.")
                offset = section[4] + address - section[3]
                return self.data[offset:offset + (size if size is not None else length)]
        raise ValueError(f"Firmware address not in ELF: {address:#x}")

    def string(self, address):
        for section in self.sections:
            if section[1] != 8 and section[2] & 2 and section[3] <= address < section[3] + section[5]:
                offset = section[4] + address - section[3]
                end = self.data.find(b"\0", offset, section[4] + section[5])
                if end < 0:
                    raise ValueError("Unterminated firmware name in ELF.")
                return self.data[offset:end].decode()
        raise ValueError(f"Firmware name address not in ELF: {address:#x}")


def verify(root, image=None):
    document = manifest(root)
    elf = Elf(image or root / "vmlinux")
    start, end = (elf.symbols[name] for name in ("__start_builtin_fw", "__end_builtin_fw"))
    if end < start or (end - start) % 24:
        raise ValueError("Invalid builtin_fw table size.")
    actual = {}
    for position in range(start, end, 24):
        name, data, size = struct.unpack("<QQQ", elf.read(position, 24))
        name = elf.string(name)
        if name in actual:
            raise ValueError(f"Duplicate builtin firmware name: {name}")
        actual[name] = (size, hashlib.sha256(elf.read(data, size)).hexdigest(), data)
    pointers = {}
    for entry in document["files"]:
        name, checksum, size = entry["name"], entry["sha256"], entry["size"]
        if name not in actual or actual[name][:2] != (size, checksum):
            raise ValueError(f"Firmware missing or corrupted inside vmlinux: {name}")
        pointer = actual[name][2]
        if pointers.setdefault(checksum, pointer) != pointer:
            raise ValueError(f"Identical firmware has multiple payloads: {name}")
    print(f"Verified {len(document['files'])} firmware names and {len(pointers)} payloads in ELF.", flush=True)


if __name__ == "__main__":
    try:
        action, directory = sys.argv[1:]
        {"prepare": prepare, "verify": verify}[action](Path(directory))
    except (ValueError, KeyError, OSError) as error:
        sys.exit(str(error))
